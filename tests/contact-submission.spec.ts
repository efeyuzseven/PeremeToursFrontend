import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.route('**/fonts.googleapis.com/**', route => route.abort())
  await page.route('**/fonts.gstatic.com/**', route => route.abort())
  await page.route('**/api/v1/**', route => route.fulfill({ status: 404, json: {} }))
})
for (const popup of [false, true]) test(`contact submission is server-side and retains drafts after failure (${popup ? 'ship' : 'page'})`, async ({ page }, testInfo) => {
  const bodies: Record<string, unknown>[] = []
  await page.route('**/api/v1/contact-requests', async route => {
    expect(route.request().method()).toBe('POST')
    bodies.push(route.request().postDataJSON())
    return route.fulfill(bodies.length === 1 ? { status: 503, json: { title: 'Unavailable' } } : { status: 202, json: { requestId: bodies.at(-1)!.requestId, status: 'Received' } })
  })
  await page.goto(popup ? '/' : '/iletisim')
  if (popup) await page.getByRole('button', { name: 'İletişim formunu aç', exact: true }).click()
  const form = page.locator('.contact-form')
  await form.getByLabel('Ad soyad', { exact: true }).fill('Fixture customer')
  await form.getByLabel('E-posta adresi', { exact: true }).fill('fixture.private@example.test')
  await form.getByLabel('Konu', { exact: true }).fill('Fixture topic')
  await form.getByLabel('Mesajın', { exact: true }).fill('Private fixture body')
  await form.getByRole('button', { name: 'Mesajı gönder' }).click()
  await expect(form.getByRole('alert')).toContainText('tekrar deneyebilirsiniz')
  await expect(form.getByLabel('Mesajın', { exact: true })).toHaveValue('Private fixture body')
  await form.getByRole('button', { name: 'Mesajı gönder' }).click()
  await expect(form.getByRole('status')).toContainText('Talebiniz alındı')
  await expect(form.getByLabel('Mesajın', { exact: true })).toHaveValue('')
  expect(bodies).toHaveLength(2); expect(bodies[0].requestId).toBe(bodies[1].requestId)
  expect(bodies[0]).toMatchObject({ name: 'Fixture customer', email: 'fixture.private@example.test', topic: 'Fixture topic', message: 'Private fixture body', language: 'tr' })
  expect(bodies[0]).not.toHaveProperty('recipients'); expect(bodies[0]).not.toHaveProperty('to')
  const storage = await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage }))
  expect(storage).not.toContain('fixture.private@example.test'); expect(storage).not.toContain('Private fixture body')
  await form.screenshot({ path: testInfo.outputPath('contact-received.png') })
  expect(await form.evaluate(node => node.scrollWidth > node.clientWidth)).toBe(false)
})
test('in-flight duplicate submissions are guarded and rate limits are clearly explained in English', async ({ page }) => {
  let count = 0
  let release: (() => void) | undefined
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.addInitScript(() => localStorage.setItem('pereme-language', 'en'))
  await page.route('**/api/v1/contact-requests', async route => { count++; await gate; return route.fulfill({ status: 429, json: {} }) })
  await page.goto('/iletisim')
  const form = page.locator('.contact-form')
  await form.getByLabel('Full name', { exact: true }).fill('Fixture')
  await form.getByLabel('Email address', { exact: true }).fill('fixture@example.test')
  await form.getByLabel('Subject', { exact: true }).fill('Fixture')
  await form.getByLabel('Your message', { exact: true }).fill('Fixture')
  await form.getByRole('button', { name: 'Send message' }).click()
  await expect(form.getByRole('button', { name: 'Sending...' })).toBeDisabled()
  await form.evaluate(node => node.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })))
  release!()
  await expect(form.getByRole('alert')).toContainText('too many requests')
  expect(count).toBe(1)
  await expect(form.getByLabel('Your message', { exact: true })).toHaveValue('Fixture')
})
